    /** Width of a string drawn with cap height `h` (character pitch is 6 units of h/7). */
    inline float getWidth (const juce::String& text, float h, float spacing = 1.0f)
    {
        const float px = h / 7.0f;
        const int n = text.length();
        return n <= 0 ? 0.0f : (n * (5.0f + spacing) - spacing - 0.5f) * px;   // glyphs are 4.5 units wide
    }

    /** Draws text with its top-left at (x, y). `bold` widens each stroke. */
    inline void drawAt (juce::Graphics& g, const juce::String& text, float x, float y, float h,
                        bool bold = false, float spacing = 1.0f)
    {
        const float px = h / 7.0f;
        const float pw = px * kPixelAspect;            // 7 columns + gap fit the old 6-unit pitch
        const float extra = bold ? pw * 0.3f : 0.0f;
        juce::RectangleList<float> rects;

        for (auto ch : text)
        {
            const auto* glyph = findGlyph ((char) (ch < 128 ? ch : '?'));
            for (int r = 0; r < 7; ++r)
            {
                const char* row = glyph->rows[r];
                int c = 0;
                while (c < 7)
                {
                    if (row[c] != '#') { ++c; continue; }
                    int runEnd = c;
                    while (runEnd < 7 && row[runEnd] == '#') ++runEnd;
                    rects.addWithoutMerging ({ x + c * pw, y + r * px, (runEnd - c) * pw + extra, px + 0.05f });
                    c = runEnd;
                }
            }
            x += (5.0f + spacing) * px;
        }
        g.fillRectList (rects);
    }

    /** Draws text inside `area` using a juce::Justification. */
    inline void draw (juce::Graphics& g, const juce::String& text, juce::Rectangle<float> area, float h,
                      juce::Justification just = juce::Justification::centredLeft, bool bold = false, float spacing = 1.0f)
    {
        const float w = getWidth (text, h, spacing);
        float x = area.getX(), y = area.getY();

        if (just.testFlags (juce::Justification::horizontallyCentred)) x = area.getCentreX() - w * 0.5f;
        else if (just.testFlags (juce::Justification::right))          x = area.getRight() - w;

        if (just.testFlags (juce::Justification::verticallyCentred))   y = area.getCentreY() - h * 0.5f;
        else if (just.testFlags (juce::Justification::bottom))         y = area.getBottom() - h;

        drawAt (g, text, x, y, h, bold, spacing);
    }
